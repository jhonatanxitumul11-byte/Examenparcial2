    private double obtenerCuota(String carrera) {
        if (carrera.equals("Ingeniería")) {
            return 930;
        } else if (carrera.equals("Arquitectura")) {
            return 1200;
        } else if (carrera.equals("Medicina")) {
            return 750;
        }
        return 0;
    }

    private void actualizarCuota() {
        if (cmbCarrera.getSelectedItem() != null) {
            double cuota = obtenerCuota(cmbCarrera.getSelectedItem().toString());
            txtCuota.setText(String.valueOf(cuota));
        }
    }

