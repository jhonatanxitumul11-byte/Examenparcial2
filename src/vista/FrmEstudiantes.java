    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {
            Estudiante p = leerFormulario();
            if (controlador.guardarEstudiante(p)) {
                JOptionPane.showMessageDialog(this, "Estudiante guardado correctamente.");
                cargarTabla();
                limpiarCampos();
            } else {
                JOptionPane.showMessageDialog(this, "No se pudo guardar el estudiante.");
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Telefono y Cuota Mensual deben ser números.");
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
        String texto = JOptionPane.showInputDialog(this, "Ingrese el ID del estudiante:");
        if (texto == null || texto.trim().isEmpty()) {
            return;
        }
        try {
            int id = Integer.parseInt(texto.trim());
            Estudiante p = controlador.consultarEstudiante(id);
            if (p != null) {
                idSeleccionado = p.getIdEstudiante();
                mostrarEstudiante(p);
            } else {
                JOptionPane.showMessageDialog(this, "Estudiante no encontrado.");
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El ID debe ser un número entero.");
        }
    }//GEN-LAST:event_btnConsultarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        if (idSeleccionado == 0) {
            JOptionPane.showMessageDialog(this, "Seleccione un estudiante de la tabla primero.");
            return;
        }
        try {
            Estudiante p = leerFormulario();
            p.setIdEstudiante(idSeleccionado);
            if (controlador.actualizarEstudiante(p)) {
                JOptionPane.showMessageDialog(this, "Estudiante actualizado.");
                cargarTabla();
                limpiarCampos();
            } else {
                JOptionPane.showMessageDialog(this, "No se pudo actualizar el estudiante.");
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Telefono y Cuota Mensual deben ser números.");
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {
        if (idSeleccionado == 0) {
            JOptionPane.showMessageDialog(this, "Seleccione un estudiante de la tabla primero.");
            return;
        }
        int respuesta = JOptionPane.showConfirmDialog(this, "¿Desea eliminar el estudiante seleccionado?", "Confirmar", JOptionPane.YES_NO_OPTION);
        if (respuesta == JOptionPane.YES_OPTION) {
            if (controlador.eliminarEstudiante(idSeleccionado)) {
                JOptionPane.showMessageDialog(this, "Estudiante eliminado.");
                cargarTabla();
                limpiarCampos();
            } else {
                JOptionPane.showMessageDialog(this, "No se pudo eliminar el estudiante.");
            }
        }
    }

    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {
        int fila = jTable1.getSelectedRow();
        if (fila >= 0) {
            idSeleccionado = Integer.parseInt(jTable1.getValueAt(fila, 0).toString());
            txtCarnet.setText(jTable1.getValueAt(fila, 1).toString());
            txtPNombre.setText(jTable1.getValueAt(fila, 2).toString());
            txtSNombre.setText(jTable1.getValueAt(fila, 3).toString());
            txtApellido.setText(jTable1.getValueAt(fila, 4).toString());
            txtDireccion.setText(jTable1.getValueAt(fila, 5).toString());
            txtTelefono.setText(jTable1.getValueAt(fila, 6).toString());
            cmbCarrera.setSelectedItem(jTable1.getValueAt(fila, 7).toString());
            actualizarCuota();
            txtNacimiento.setText(jTable1.getValueAt(fila, 8).toString());
            txtIngreso.setText(jTable1.getValueAt(fila, 9).toString());
            txtCuota.setText(jTable1.getValueAt(fila, 10).toString());
        }
    }

    private Estudiante leerFormulario() {
        Estudiante p = new Estudiante();
        p.setCarnet(txtCarnet.getText().trim());
        p.setFirstName(txtPNombre.getText().trim());
        p.setSecondName(txtSNombre.getText().trim());
        p.setLastName(txtApellido.getText().trim());
        p.setDireccion(txtDireccion.getText().trim());
        p.setTelefono(Integer.parseInt(txtTelefono.getText().trim()));
        p.setCarrera(cmbCarrera.getSelectedItem().toString());
        p.setFechaNacimiento(txtNacimiento.getText().trim());
        p.setFechaIngreso(txtIngreso.getText().trim());
        p.setCuotaMensual(obtenerCuota(cmbCarrera.getSelectedItem().toString()));
        return p;
    }

    private void mostrarEstudiante(Estudiante p) {
        txtCarnet.setText(p.getCarnet());
        txtPNombre.setText(p.getFirstName());
        txtSNombre.setText(p.getSecondName());
        txtApellido.setText(p.getLastName());
        txtDireccion.setText(p.getDireccion());
        txtTelefono.setText(String.valueOf(p.getTelefono()));
        cmbCarrera.setSelectedItem(p.getCarrera());
        actualizarCuota();
        txtNacimiento.setText(p.getFechaNacimiento());
        txtIngreso.setText(p.getFechaIngreso());
        txtCuota.setText(String.valueOf(p.getCuotaMensual()));
    }

    private void cargarTabla() {
        modeloTabla.setRowCount(0);
        for (Estudiante p : controlador.obtenerEstudiantes()) {
            modeloTabla.addRow(new Object[]{
                p.getIdEstudiante(), p.getCarnet(), p.getFirstName(), p.getSecondName(),
                p.getLastName(), p.getDireccion(), p.getTelefono(), p.getCarrera(),
                p.getFechaNacimiento(), p.getFechaIngreso(), p.getCuotaMensual()
            });
        }
    }

    private void limpiarCampos() {
        idSeleccionado = 0;
        txtCarnet.setText("");
        txtPNombre.setText("");
        txtSNombre.setText("");
        txtApellido.setText("");
        txtDireccion.setText("");
        txtTelefono.setText("");
        cmbCarrera.setSelectedIndex(0);
        txtNacimiento.setText("");
        txtIngreso.setText("");
        actualizarCuota();
        jTable1.clearSelection();
    }

